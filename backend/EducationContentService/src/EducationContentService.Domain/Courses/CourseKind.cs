namespace EducationContentService.Domain.Courses;

/// <summary>
///     Тип курса: полноценный курс или интенсив.
    ///     Интенсив — мини-курс без заданий (только модули + материалы), продаётся отдельным COURSE-планом
    ///     либо включён в платформенный FULL_ALL/LEARN_ALL. Материалы интенсива могут шариться с основными курсами,
    ///     поэтому full-access юзеры видят их через родительский курс и не нуждаются в показе интенсива
///     отдельной карточкой в dashboard'е.
/// </summary>
public enum CourseKind
{
    /// <summary>Полноценный курс — модули + материалы + задания.</summary>
    COURSE,

    /// <summary>Интенсив — модули + материалы, без заданий.</summary>
    INTENSIVE,

    /// <summary>Марафон — когортный мини-курс/записи занятий: модули + материалы, без заданий.</summary>
    MARATHON
}
